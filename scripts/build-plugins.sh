#!/usr/bin/env bash
# Build every plugin under plugins/ for wasm32-unknown-unknown, pack each into
# a component, and write two registries beside them in target/plugins/:
#
#   registry.toml       first-party plugins only — what a relay ships with
#   registry.test.toml  first-party plus the test plugins (fixture, faults)
#
# The webhook-plugin@1 fixture (test-webhook.wasm) is built but in neither
# registry: loading a webhook plugin needs an application-event validator,
# which the relay and `beekeeper-plugin-run` do not configure yet. Its tests
# write their own registry for it.
#
# Each entry pins the component's sha256, so a registry and the files beside
# it are only valid together. A relay that is pointed at a registry and finds a
# different file refuses to start.
#
# Usage: scripts/build-plugins.sh [out-dir] [--first-party-only]
#   out-dir             default <target>/plugins
#   --first-party-only  skip the test plugins (what a relay image ships)
# BEEKEEPER_PLUGIN_PACK names a prebuilt `beekeeper-plugin-pack` to use
# instead of building one (the Docker image builds it in release).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
target="${CARGO_TARGET_DIR:-$root/target}"
out="$target/plugins"
first_party_only=false
for arg in "$@"; do
  case "$arg" in
    --first-party-only) first_party_only=true ;;
    *) out="$arg" ;;
  esac
done
build_dir="$target/plugin-build"
mkdir -p "$out"

# The pack tool is a normal host binary from the root workspace.
if [[ -n "${BEEKEEPER_PLUGIN_PACK:-}" ]]; then
  pack="$BEEKEEPER_PLUGIN_PACK"
else
  cargo build --quiet -p beekeeper-plugin-tools --bin beekeeper-plugin-pack
  pack="$target/debug/beekeeper-plugin-pack"
fi

# name:dir:first-party (yes / no / unregistered)
plugins=(
  "planning:plugins/planning:yes"
  "planning-fixture:plugins/test-planning-fixture:no"
  "test-faults:plugins/test-faults:no"
  "test-webhook:plugins/test-webhook:unregistered"
)

first_party=""
test_only=""
for spec in "${plugins[@]}"; do
  IFS=: read -r name dir shipped <<<"$spec"
  if [[ "$first_party_only" == true && "$shipped" != yes ]]; then
    continue
  fi
  manifest="$root/$dir/Cargo.toml"
  crate="$(sed -n 's/^name *= *"\(.*\)"/\1/p' "$manifest" | head -1)"
  CARGO_TARGET_DIR="$build_dir" cargo build --quiet --release --locked \
    --target wasm32-unknown-unknown --manifest-path "$manifest"
  core="$build_dir/wasm32-unknown-unknown/release/${crate//-/_}.wasm"
  sha="$("$pack" "$core" "$out/$name.wasm")"
  echo "plugin $name: $out/$name.wasm sha256 $sha"
  world="operation-provider@1"
  case "$name" in
    planning)
      grants=$'[plugin.grants]\nread_kinds = [44248]\ndraft_kinds = [44248]'
      limits=""
      ;;
    planning-fixture)
      grants=$'[plugin.grants]\nread_kinds = []\ndraft_kinds = [44248]'
      limits=""
      ;;
    test-faults)
      grants=$'[plugin.grants]\nread_kinds = [44248]\ndraft_kinds = [44248]'
      # Small enough that `spin` and `grow` stop quickly.
      limits=$'[plugin.limits]\nfuel = 200000000\nmemory_bytes = 33554432\nmax_queries = 5\nmax_output_bytes = 1048576'
      ;;
    test-webhook)
      world="webhook-plugin@1"
      grants=$'[plugin.grants]\ntype_prefix = "com.example"'
      # Small enough that `spin` stops quickly.
      limits=$'[plugin.limits]\nfuel = 200000000\nmemory_bytes = 33554432'
      ;;
  esac
  entry="[[plugin]]
name = \"$name\"
world = \"$world\"
path = \"$name.wasm\"
sha256 = \"$sha\"
$grants
$limits
"
  if [[ "$shipped" == unregistered ]]; then
    continue
  fi
  if [[ "$shipped" == yes ]]; then
    first_party+="$entry"$'\n'
  fi
  test_only+="$entry"$'\n'
done

header="# Generated by scripts/build-plugins.sh — do not edit; rebuild instead."
printf '%s\n\n%s' "$header" "$first_party" >"$out/registry.toml"
if [[ "$first_party_only" == true ]]; then
  echo "registry: $out/registry.toml"
  exit 0
fi
printf '%s\n# Includes test-only plugins. Never deploy this file.\n\n%s' "$header" "$test_only" >"$out/registry.test.toml"
echo "registries: $out/registry.toml $out/registry.test.toml"

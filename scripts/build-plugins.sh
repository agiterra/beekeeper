#!/usr/bin/env bash
# Build every plugin under plugins/ for wasm32-unknown-unknown, pack each into
# a component, and write two registries beside them in target/plugins/:
#
#   registry.toml       first-party plugins only — what a relay ships with
#   registry.test.toml  first-party plus the test plugins (fixture, faults)
#
# Each entry pins the component's sha256, so a registry and the files beside
# it are only valid together. A relay that is pointed at a registry and finds a
# different file refuses to start.
#
# Usage: scripts/build-plugins.sh [out-dir]   (default target/plugins)
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="${1:-$root/target/plugins}"
build_dir="$root/target/plugin-build"
mkdir -p "$out"

# The pack tool is a normal host binary from the root workspace.
cargo build --quiet -p beekeeper-plugin-tools --bin beekeeper-plugin-pack
pack="$root/target/debug/beekeeper-plugin-pack"

# name:dir:first-party
plugins=(
  "planning:plugins/planning:yes"
  "planning-fixture:plugins/test-planning-fixture:no"
  "test-faults:plugins/test-faults:no"
)

first_party=""
test_only=""
for spec in "${plugins[@]}"; do
  IFS=: read -r name dir shipped <<<"$spec"
  manifest="$root/$dir/Cargo.toml"
  crate="$(sed -n 's/^name *= *"\(.*\)"/\1/p' "$manifest" | head -1)"
  CARGO_TARGET_DIR="$build_dir" cargo build --quiet --release \
    --target wasm32-unknown-unknown --manifest-path "$manifest"
  core="$build_dir/wasm32-unknown-unknown/release/${crate//-/_}.wasm"
  sha="$("$pack" "$core" "$out/$name.wasm")"
  echo "plugin $name: $out/$name.wasm sha256 $sha"
  case "$name" in
    planning)
      grants=$'[plugin.grants]\nread_kinds = [44248]\ndraft_kinds = [44248]'
      limits=""
      ;;
    planning-fixture)
      grants=$'[plugin.grants]\nread_kinds = []\ndraft_kinds = []'
      limits=""
      ;;
    test-faults)
      grants=$'[plugin.grants]\nread_kinds = [44248]\ndraft_kinds = [44248]'
      # Small enough that `spin` and `grow` stop quickly.
      limits=$'[plugin.limits]\nfuel = 200000000\nmemory_bytes = 33554432\nmax_queries = 5\nmax_output_bytes = 1048576'
      ;;
  esac
  entry="[[plugin]]
name = \"$name\"
world = \"operation-provider@1\"
path = \"$name.wasm\"
sha256 = \"$sha\"
$grants
$limits
"
  if [[ "$shipped" == yes ]]; then
    first_party+="$entry"$'\n'
  fi
  test_only+="$entry"$'\n'
done

header="# Generated by scripts/build-plugins.sh — do not edit; rebuild instead."
printf '%s\n\n%s' "$header" "$first_party" >"$out/registry.toml"
printf '%s\n# Includes test-only plugins. Never deploy this file.\n\n%s' "$header" "$test_only" >"$out/registry.test.toml"
echo "registries: $out/registry.toml $out/registry.test.toml"

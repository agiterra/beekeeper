//! Terminal decisions are durable before any disclosure effect. Uncertain
//! transport/target resolution never converts a refusal back into a hire.
use crate::{
    hire::{Adapter, Disposition, Scope},
    management::local::{fail, save, Operation},
    Error, RelayTransport,
};
use beekeeper_core::coding_session_command::{
    CodingSessionAction, CodingSessionCommandPayload, CodingSessionDelivery,
    CODING_SESSION_COMMAND_SCHEMA,
};
use nostr::{Event, Tag};
use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct Decision {
    code: String,
    reason: String,
    disclosure: Option<Event>,
    pub(crate) acknowledged: bool,
}
impl Decision {
    pub(crate) fn new(reason: String) -> Self {
        let (code, detail) = reason.split_once(':').unwrap_or((
            &reason,
            "A new request is required after correcting the selection or policy.",
        ));
        let valid = code.starts_with("HIRE_")
            && code
                .bytes()
                .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_');
        Self {
            code: if valid {
                code.into()
            } else {
                "HIRE_UNAVAILABLE".into()
            },
            reason: if valid {
                detail.trim().chars().take(1024).collect()
            } else {
                "The selected role, runtime or checkout is unavailable. A new request is required."
                    .into()
            },
            disclosure: None,
            acknowledged: false,
        }
    }
}
pub(crate) fn operation(binding: serde_json::Value, reason: String) -> Operation {
    Operation {
        request: binding,
        actor_pubkey: String::new(),
        events: vec![],
        target: None,
        receipt_event_id: None,
        predecessor: None,
        custody_handoff: None,
        hire: None,
        hire_decision: Some(Decision::new(reason)),
    }
}
pub(crate) async fn reconcile(
    path: &Path,
    operation: &mut Operation,
    client: &impl RelayTransport,
    adapter: &impl Adapter,
    scope: &Scope,
    request: &Event,
) -> Result<Disposition, Error> {
    let mut decision = operation
        .hire_decision
        .clone()
        .ok_or_else(|| fail("terminal hire decision missing"))?;
    if decision.disclosure.is_none() {
        if let Ok(target) = adapter.refusal_target(scope, request).await {
            let payload = CodingSessionCommandPayload {
                schema: CODING_SESSION_COMMAND_SCHEMA.into(), command_id: uuid::Uuid::new_v4().to_string(), target,
                action: CodingSessionAction::ThreadTurnStart {
                    text: format!("hire refused: {} — {} [Host notice — not a person: generated by this computer's host process, never typed by an operator]", decision.code, decision.reason),
                    attachments: vec![], deliver: CodingSessionDelivery::Boundary,
                },
            };
            let event = beekeeper_sdk::build_coding_session_command(scope.channel, &payload)
                .map_err(fail)?
                .tags([Tag::parse([
                    beekeeper_core::coding_session_payload::CODING_SESSION_HOST_ANSWER_TAG_NAME,
                    beekeeper_core::coding_session_payload::CODING_SESSION_HOST_ANSWER_TAG_HIRE,
                ])
                .map_err(fail)?])
                .sign_with_keys(client.keys())
                .map_err(fail)?;
            decision.disclosure = Some(event);
            operation.hire_decision = Some(decision.clone());
            save(path, operation)?;
        }
    }
    if let Some(event) = &decision.disclosure {
        if !decision.acknowledged {
            // No replacement event after ACK loss: retransmit the stored bytes.
            // A failed ACK keeps disclosure pending but never releases the decision.
            if crate::management::submit(client, event).await.is_ok() {
                decision.acknowledged = true;
                operation.hire_decision = Some(decision.clone());
                save(path, operation)?;
            }
        }
    }
    Ok(Disposition::PolicyRefused {
        code: decision.code,
        reason: decision.reason,
        disclosure_event_id: decision.disclosure.map(|e| e.id.to_hex()),
        disclosure_confirmed: decision.acknowledged,
    })
}
